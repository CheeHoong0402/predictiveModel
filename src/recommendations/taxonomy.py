class DataQualityStatus(str, Enum):
    GOOD = "GOOD"
    ACCEPTABLE_WITH_WARNINGS = "ACCEPTABLE_WITH_WARNINGS"
    LIMITED_HISTORY = "LIMITED_HISTORY"
    MISSING_OPTIONAL_DATA = "MISSING_OPTIONAL_DATA"
    INSUFFICIENT_DATA = "INSUFFICIENT_DATA"
    REJECTED = "REJECTED"


VALID_ACTIONS: Set[str] = {a.value for a in ActionType}
VALID_URGENCIES: Set[str] = {u.value for u in UrgencyLevel}
VALID_ROBUSTNESS: Set[str] = {r.value for r in RobustnessStatus}
VALID_REASON_CODES: Set[str] = {rc.value for rc in ReasonCode}
VALID_DATA_QUALITIES: Set[str] = {dq.value for dq in DataQualityStatus}


def is_valid_action(action: str) -> bool:
    return action in VALID_ACTIONS


def is_valid_urgency(urgency: str) -> bool:
    return urgency in VALID_URGENCIES


def is_valid_robustness(status: str) -> bool:
    return status in VALID_ROBUSTNESS


def is_valid_reason_code(code: str) -> bool:
    return code in VALID_REASON_CODES


def is_valid_data_quality_status(status: str) -> bool:
    return status in VALID_DATA_QUALITIES
